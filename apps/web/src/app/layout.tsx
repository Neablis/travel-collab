// Where absolute URLs in metadata (og:image, og:url) resolve from. Vercel's
// documented hierarchy, written out rather than left to Next's default so a
// framework-version change can't silently alter what scrapers see: the
// production domain in production, the deployment's own URL on previews (so
// a shared preview link unfurls with an og:image that actually loads —
// production may not exist yet), localhost otherwise.
// Moved to `lib/deploymentOrigin.ts` when `app/admin/page.tsx` needed the same
// rule to build a credential-bearing URL — two copies of an origin hierarchy
// drift, and the copy that drifts is the one nobody is looking at.
const metadataBase = new URL(deploymentOrigin());

// iOS's launch screens (M54 decision 7): the files `scripts/generate-og-assets.mjs`
// draws, one per portrait screen, as `[CSS width, CSS height, pixel ratio]`. iOS
// takes the one whose media query matches the device exactly and shows nothing
// otherwise. `layout.test.ts` holds this list to the files.
const STARTUP_SCREENS: readonly (readonly [number, number, number])[] = [
  [440, 956, 3], [402, 874, 3], [430, 932, 3], [393, 852, 3], [428, 926, 3], [390, 844, 3],
  [375, 812, 3], [414, 896, 3], [414, 896, 2], [414, 736, 3], [375, 667, 2], [320, 568, 2],
  [1032, 1376, 2], [1024, 1366, 2], [834, 1210, 2], [834, 1194, 2], [820, 1180, 2], [810, 1080, 2],
  [768, 1024, 2], [744, 1133, 2],
];

// og:image, og:image:alt and twitter:image come from the file conventions
// next to this layout (src/app/opengraph-image.png + .alt.txt, and icon.svg
// for the favicon — all regenerated by scripts/generate-og-assets.mjs), so
// they are deliberately not repeated here. Pages that need their own
// title/description go through lib/siteMetadata.ts's pageMetadata() — see
// the merge gotcha documented there.
export const metadata: Metadata = {
  metadataBase,
  title: { default: SITE_NAME, template: `%s — ${SITE_NAME}` },
  description: SITE_DESCRIPTION,
  openGraph: {
    siteName: SITE_NAME,
    type: "website",
    locale: "en_US",
    title: SITE_NAME,
    description: SITE_DESCRIPTION,
  },
  twitter: { card: "summary_large_image" },
  robots: siteRobots(),
  // `appleWebApp.capable` renders only the unprefixed `mobile-web-app-capable`,
  // and iOS has honoured `apple-touch-startup-image` only beside the Apple one.
  other: { "apple-mobile-web-app-capable": "yes" },
  appleWebApp: {
    capable: true,
    startupImage: STARTUP_SCREENS.map(([width, height, ratio]) => ({
      url: `/icons/startup-${width * ratio}x${height * ratio}.png`,
      media: `(device-width: ${width}px) and (device-height: ${height}px) and (-webkit-device-pixel-ratio: ${ratio}) and (orientation: portrait)`,
    })),
  },
};

// M39 D10: `viewport-fit=cover` lets the installed app draw under a notch, a
// status bar and a home indicator, and ships together with the insets that keep
// the chrome out from under them (globals.css, "The device's safe area"). With
// `cover` and no insets an installed iPhone app draws its header under the
// status bar; with insets and no `cover` they are all 0 and do nothing.
// `width` and `initialScale` are Next's defaults, written out so this export
// reads as the whole tag. `themeColor` colours the browser's bar, the
// manifest's `theme_color` the installed app's — the same token.
//
// `interactiveWidget`: since Chrome 108 Android's keyboard resizes only the
// visual viewport, so `dvh` and a fixed `bottom: 0` stay where they were and
// the phone sheet's composer, Chat's and Ask's alike, sat under the keyboard
// (Mitchell, PR 436's preview). `resizes-content` shrinks the layout instead,
// which is what the sheet's and the rail's `dvh` were written expecting. The
// cost is app-wide on Android: anything fixed to the bottom, the tab bar
// included, rides up above the keyboard too. iOS Safari ignores the key.
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
  interactiveWidget: "resizes-content",
  themeColor: appColors.surface,
};

// SPEC §35.1: Ledger is the only look. The other three and the theme switch
// were deleted, and no picker will ever exist — so this is a constant, not a
// preference, and nothing reads or stores a look.
//
// Written on `<html>` in the server-rendered markup rather than by an effect,
// so the first paint is already Ledger. A client-side write would flash the
// base `@theme` palette on every cold load.
//
// The attribute stays rather than folding Ledger into `@theme` (M27 D1): the
// OG generator reads the first `--color-*` match in `globals.css`, and a fold
// would change every generated asset for no visible gain.
const LOOK = "ledger";

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // `suppressHydrationWarning` for the one attribute React does not render
    // here: `LAUNCH_SCRIPT` adds `data-launch` before hydration on a home-screen
    // launch or the first page after a sign-in. It reaches this element's own
    // attributes only.
    <html
      lang="en"
      data-look={LOOK}
      className={fontVariables}
      suppressHydrationWarning
    >
      <head>
        {/* Before any bundle, so an install offer fired early is held for
            `InstallPromptRegistration` rather than lost (installPrompt.ts). */}
        <script dangerouslySetInnerHTML={{ __html: EARLY_INSTALL_LISTENER }} />
        {/* A signed-in browser on the static landing goes to Home before it
            paints (ADR-078); a no-op on every other path. */}
        <script dangerouslySetInnerHTML={{ __html: LEAVE_LANDING_IF_SIGNED_IN }} />
        {/* Marks a home-screen launch, or the first page after a sign-in,
            before the body paints, so the launch overlay below covers the
            first frame (M54 decisions 6 and 19). */}
        <script dangerouslySetInnerHTML={{ __html: LAUNCH_SCRIPT }} />
        {/* Cover photos are hot-linked from Unsplash's CDN (`CoverImage`), and
            on Home and a trip the cover is the page's largest paint, so the
            connection is opened before the first one is asked for. No
            `crossOrigin`, on purpose: the `<img>` carries none, so it fetches
            in no-cors mode, and an anonymous-CORS preconnect would warm a
            different connection from the one the image then uses. */}
        <link rel="preconnect" href="https://images.unsplash.com" />
      </head>
      <body>
        {/* First in the body, so on a home-screen launch or the first page
            after a sign-in it is the first thing painted, over the page as it
            streams in. Drawn by nothing else. */}
        <LaunchOverlay />
        {/* Above the header AND the page, because the header's logo is the
            save light and the state it shows is published from inside the
            trip below (SaveLight.tsx). AppHeader itself no longer renders
            here — the (app) route group's own layout renders it, nested
            inside this provider — but the front door (/, /signin,
            /signup) renders through this same slot with no AppHeader at all,
            so this provider wraps both: a save light with no consumer where
            there's no header, and the real one where (app)/layout.tsx
            supplies it. A client provider here does not make this layout a
            client component — `children` is still passed through as an
            already-rendered server tree. */}
        {/* The front door's route cross-fade (decision 18, ADR-082 §3): it
            has no `AppShell`, so its pages fade here. An app page's own
            boundaries are nested inside this one, and claim its changes. */}
        <SaveLightProvider>
          <RouteViewTransition>{children}</RouteViewTransition>
        </SaveLightProvider>
        <ServiceWorkerRegistration />
        <InstallPromptRegistration />
        {/* Only on Vercel. Both packages gate themselves on `isDevelopment()`
            alone, so any production build — `next start` locally, CI's
            ci-like e2e lane, a self-hosted deploy — mounted them and then
            requested `/_vercel/insights/script.js` and
            `/_vercel/speed-insights/script.js`, which only Vercel's edge ever
            serves. Off Vercel that is two 404s plus two strict-MIME refusals
            in the console on every page: 34 of the 2026-09-05 review's ~70
            browser-walk finding lines, burying real errors and making a "no
            console errors" e2e assertion impossible (KI-2026-09-05-y /
            F-G06). `VERCEL` is set by the platform on every Vercel build and
            runtime and by nothing else, which is also the condition
            next.config.ts's CSP comment already assumes when it calls these
            scripts same-origin. Read per render, not hoisted to a module
            constant, so layout.test.ts can exercise both branches. */}
        {process.env.VERCEL ? (
          <>
            <Analytics />
            <SpeedInsights />
          </>
        ) : null}
      </body>
    </html>
  );
}
