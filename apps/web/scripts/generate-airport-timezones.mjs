// Regenerates `src/server/airportTimeZones.generated.ts`: IATA airport code →
// IANA time zone, for `TripGlobals.homeTimeZone` (M14 link 11).
//
// **Two sources, both named in the output's header, both chosen for licence**
// (M14's "Decided 2026-09-24" defaults):
//
// - Airports and their coordinates: OurAirports' `airports.csv`, which its
//   maintainers dedicate to the public domain. Every row with a three-letter
//   `iata_code` is kept, whatever its type — the account field is regex-checked
//   and never looked up, so a small field somebody really flies from must still
//   resolve.
// - The zone at those coordinates: `geo-tz` (MIT) over timezone-boundary-builder
//   (ODbL-1.0). OurAirports carries no time zone column, so one is computed.
//
// **Why `geo-tz` here and `@photostructure/tz-lookup` at runtime.** geo-tz is
// the accurate one and is ~70 MB; tz-lookup is ~30 kB gzipped and lossy. Run
// over all 9,054 IATA airports on 2026-09-24, tz-lookup disagreed with geo-tz on
// the UTC offset (January or July) for 166 of them — six large airports among
// them. A table computed once, offline, costs nothing at runtime, so it gets the
// accurate lookup and the runtime keeps the small one. geo-tz is therefore NOT a
// dependency of this repo: install it somewhere scratch and point at it.
//
// Usage (from the repo root):
//
//   mkdir -p /tmp/geotz && (cd /tmp/geotz && npm i geo-tz@8)
//   curl -sSLo /tmp/airports.csv \
//     https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv
//   GEO_TZ_FROM=/tmp/geotz node apps/web/scripts/generate-airport-timezones.mjs /tmp/airports.csv
//
// The output groups codes by zone and concatenates them, three letters each —
// ~38 kB of source rather than ~250 kB for a `{ "SFO": "America/Los_Angeles" }`
// object, and it parses into a Map once, on first lookup.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const [csvPath] = process.argv.slice(2);
if (!csvPath || !process.env.GEO_TZ_FROM) {
  console.error("usage: GEO_TZ_FROM=<dir with geo-tz installed> node generate-airport-timezones.mjs <airports.csv>");
  process.exit(2);
}
const geoTzDir = path.join(path.resolve(process.env.GEO_TZ_FROM), "node_modules/geo-tz");
const { find } = createRequire(path.join(geoTzDir, "noop.js"))(path.join(geoTzDir, "dist/find-all.js"));
const geoTzVersion = JSON.parse(readFileSync(path.join(geoTzDir, "package.json"), "utf8")).version;

// RFC 4180, which is all OurAirports emits: quoted fields may hold commas and
// doubled quotes, never newlines in the columns read here.
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field !== "" || row.length > 0) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(readFileSync(csvPath, "utf8"));
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`airports.csv has no ${name} column`);
  return i;
};
const IATA = col("iata_code"), LAT = col("latitude_deg"), LNG = col("longitude_deg");

const byZone = new Map();
const seen = new Set();
for (const row of rows) {
  const code = row[IATA];
  if (!/^[A-Z]{3}$/.test(code ?? "") || seen.has(code)) continue;
  const lat = Number(row[LAT]), lng = Number(row[LNG]);
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) continue;
  const [zone] = find(lat, lng);
  if (!zone) continue;
  seen.add(code);
  (byZone.get(zone) ?? byZone.set(zone, []).get(zone)).push(code);
}

const zones = [...byZone.keys()].sort();
const body = zones.map((zone) => `  ${JSON.stringify(zone)}: "${byZone.get(zone).sort().join("")}",`).join("\n");
const out = `// GENERATED by apps/web/scripts/generate-airport-timezones.mjs — do not edit by hand.
//
// IATA airport code → IANA time zone, ${seen.size} airports in ${zones.length} zones.
//
// Sources:
// - Airports and coordinates: OurAirports airports.csv
//   (https://ourairports.com/data/), dedicated to the public domain.
// - Zones: geo-tz ${geoTzVersion} (MIT) over timezone-boundary-builder
//   (https://github.com/evansiroky/timezone-boundary-builder), whose data is
//   licensed under the Open Database License (ODbL-1.0). This table is derived
//   from it and is made available under the same licence.
//
// Each value is that zone's airport codes concatenated, three letters each.
export const AIRPORT_CODES_BY_ZONE: Readonly<Record<string, string>> = {
${body}
};
`;
const target = path.join(path.dirname(new URL(import.meta.url).pathname), "../src/server/airportTimeZones.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${seen.size} airports in ${zones.length} zones to ${path.relative(process.cwd(), target)}`);
