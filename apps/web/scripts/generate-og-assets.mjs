// Regenerates the two committed brand assets the App Router serves via its
// file conventions:
//
//   src/app/opengraph-image.png  (1200×630, og:image / twitter:image)
//   src/app/icon.svg             (favicon)
//
// Run from apps/web:  node scripts/generate-og-assets.mjs
//
// Why a committed PNG instead of an ImageResponse route: the color wall
// (scripts/check-color-wall.mjs) allows raw color literals in exactly one
// file, src/app/globals.css — and satori can't resolve CSS custom
// properties, so an opengraph-image.tsx would need its own hex literals.
// This script keeps globals.css the single source of color truth by parsing
// the tokens out of it at generation time; a palette change means re-running
// this script, not editing a second copy of the palette.
//
// Rendering happens in a real Chromium (Playwright, already a devDependency)
// rather than satori so the card can use the same Google-served fonts the
// app loads via next/font. The font files are fetched here in Node and
// embedded as data: URLs — the browser itself may sit behind a proxy it
// doesn't trust, and a silent fallback-font render is exactly the failure
// this avoids. If the fetch fails, the script fails; re-run with network.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const root = new URL("../", import.meta.url);
const globalsCss = readFileSync(fileURLToPath(new URL("src/app/globals.css", root)), "utf8");

function token(name) {
  const m = globalsCss.match(new RegExp(`--color-${name}:\\s*(#[0-9a-fA-F]{3,8})\\b`));
  if (!m) throw new Error(`token --color-${name} not found in globals.css`);
  return m[1];
}

const c = {
  paper: token("paper"),
  surface: token("surface"),
  moss: token("moss"),
  hairline: token("hairline"),
  slate: token("slate"),
  ink: token("ink"),
  brand: token("brand"),
  brandTint: token("brand-tint"),
  infoTint: token("info-tint"),
  warningTint: token("warning-tint"),
};

