// Regenerates the committed brand assets:
//
//   src/app/opengraph-image.png  (1200×630, og:image / twitter:image)
//   src/app/icon.svg             (favicon)
//   src/app/apple-icon.png       (180×180, iOS home screen)
//   public/icons/icon-*-v2.png   (192, 512 and maskable 512, app/manifest.ts)
//
// Run from apps/web:  node scripts/generate-og-assets.mjs
//
// Why a committed PNG instead of an ImageResponse route: the color wall
// (scripts/check-color-wall.mjs) allows raw color literals in exactly one
// file, src/app/globals.css — and satori can't resolve CSS custom
// properties, so an opengraph-image.tsx would need its own hex literals.
// This script keeps globals.css the single source of color truth by parsing
// the tokens out of it at generation time; a palette change means re-running
// this script, not editing a second copy of the palette.
//
// The per-link cards (`src/app/api/og/**`) ARE ImageResponse routes, since
// spec 2026-09-27: they get the same literals through a generated module,
// `src/server/og/ogTokens.generated.ts`, which the wall exempts and a test
// holds to globals.css. This site-wide card stays a committed PNG.
//
// Rendering happens in a real Chromium (Playwright, already a devDependency)
// rather than satori so the card can use the same Google-served fonts the
// app loads via next/font. The font files are fetched here in Node and
// embedded as data: URLs — the browser itself may sit behind a proxy it
// doesn't trust, and a silent fallback-font render is exactly the failure
// this avoids. If the fetch fails, the script fails; re-run with network.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { ledgerColorToken, readOgColors } from "./lib/ogTokens.mjs";

const root = new URL("../", import.meta.url);
const globalsCss = readFileSync(fileURLToPath(new URL("src/app/globals.css", root)), "utf8");

// The parser is shared with `generate-og-tokens.mjs`, which feeds the per-link
// preview cards the same colours (spec 2026-09-27 §2.2).
const c = readOgColors(globalsCss);

// ---------------------------------------------------------------------------
// The brand mark — the caesura, two upright strokes on a brand tile (SPEC §28)
// — as geometry, so it doesn't depend on any font. `BrandMark.tsx` is the one
// place its proportions are decided; these are its ratios, at its default
// 32px tile: stroke width and gap `size / 8`, stroke height `size * 0.5625`,
// centred. Copied rather than imported because this script cannot load TSX;
// `src/app/brandIcons.test.ts` holds the output to the mark's shape.
//
// Colours and corners are the LEDGER look's, because that is what the live
// header paints (`layout.tsx`'s `LOOK`): its brand green, its surface for the
// strokes, and a square tile — Ledger takes `--radius-xs` (BrandMark's 4px) to
// 0. `colorToken` would read the `@theme` defaults instead, which is how these
// icons kept the pre-Ledger green; `appColors.generated.ts` reads the same
// block for the manifest's colours.
const markBrand = ledgerColorToken(globalsCss, "brand");
const markSurface = ledgerColorToken(globalsCss, "surface");
const MARK = 32;
const STROKE = MARK / 8;
const STROKE_HEIGHT = MARK * 0.5625;
const strokeX = (MARK - 3 * STROKE) / 2;
const strokeY = (MARK - STROKE_HEIGHT) / 2;
const markRects = [strokeX, strokeX + 2 * STROKE]
  .map((x) => `<rect x="${x}" y="${strokeY}" width="${STROKE}" height="${STROKE_HEIGHT}" fill="${markSurface}"/>`)
  .join("\n  ");
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${MARK} ${MARK}">
  <!-- Generated by scripts/generate-og-assets.mjs from globals.css tokens.
       Do not hand-edit; change BrandMark.tsx's ratios or globals.css and re-run. -->
  <rect width="${MARK}" height="${MARK}" fill="${markBrand}"/>
  ${markRects}
</svg>
`;
writeFileSync(fileURLToPath(new URL("src/app/icon.svg", root)), iconSvg);
console.log("wrote src/app/icon.svg");

// ---------------------------------------------------------------------------
// The installed app's icons (M39 Part 4): the same mark as PNGs, because a
// manifest needs raster icons at 192 and 512 for Chrome to offer an install,
// and iOS takes its home-screen icon from `apple-icon.png` only.
//
// One shape for all four: the Ledger tile is already a full-bleed square, which
// is what the maskable icon and Apple's need (the OS cuts its own shape, and a
// transparent corner shows black on iOS). The maskable spec keeps everything
// that matters inside a circle of radius 40% of the icon; the strokes' far
// corners sit at hypot(6, 9) / 32 ≈ 34% from the centre, so the favicon's
// geometry is already inside it with no rescaling.
//
// The 192/512 set lives in `public/icons/` and is named by the manifest. Its
// filenames carry a version (`-v2`, the strokes; unversioned was ◎): an
// installed Android app picks up a changed icon through Chrome's periodic
// manifest check, and a new URL makes the change unambiguous where a same-named
// file relies on byte comparison. Bump it whenever the mark changes, with
// `app/manifest.ts` (the service worker caches nothing, KI-2026-10-09-e, so
// there is no cache to bump). `apple-icon.png` and
// `icon.svg` use App Router file conventions, which add their own cache-busting
// query, so they keep their names.
const ICON_VERSION = "v2";
const appIcons = [
  [`public/icons/icon-192-${ICON_VERSION}.png`, 192],
  [`public/icons/icon-512-${ICON_VERSION}.png`, 512],
  [`public/icons/icon-maskable-512-${ICON_VERSION}.png`, 512],
  ["src/app/apple-icon.png", 180],
];
{
  mkdirSync(fileURLToPath(new URL("public/icons/", root)), { recursive: true });
  const browser = await chromium.launch();
  for (const [path, size] of appIcons) {
    const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
    const src = `data:image/svg+xml;base64,${Buffer.from(iconSvg).toString("base64")}`;
    await page.setContent(`<body style="margin:0"><img src="${src}" width="${size}" height="${size}" style="display:block">`);
    await page.locator("img").evaluate((img) => img.decode());
    await page.screenshot({ path: fileURLToPath(new URL(path, root)), type: "png", omitBackground: true });
    await page.close();
    console.log(`wrote ${path}`);
  }
  await browser.close();
}

