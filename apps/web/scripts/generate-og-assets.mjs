// Fonts, matching layout.tsx's next/font loads (display + sans subsets the
// card actually uses). A Chrome UA gets woff2 sources from the css2 endpoint.
async function inlineFontCss(family, weights) {
  const url = `https://fonts.googleapis.com/css2?family=${family.replaceAll(" ", "+")}:wght@${weights.join(";")}&display=swap`;
  const css = await (await fetch(url, { headers: { "user-agent": "Mozilla/5.0 Chrome/120" } })).text();
  const fontUrls = [...new Set([...css.matchAll(/url\((https:[^)]+)\)/g)].map((m) => m[1]))];
  let inlined = css;
  for (const fontUrl of fontUrls) {
    const bytes = Buffer.from(await (await fetch(fontUrl)).arrayBuffer());
    const mime = fontUrl.endsWith(".woff2") ? "font/woff2" : "font/ttf";
    inlined = inlined.replaceAll(fontUrl, `data:${mime};base64,${bytes.toString("base64")}`);
  }
  return inlined;
}
